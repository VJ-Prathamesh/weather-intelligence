def load_data():
    frames, meta = [], {}
    for path in sorted(glob.glob(os.path.join(RAW_DIR, "*.csv"))):
        city = os.path.basename(path).split("_weather")[0]
        lat, lon, elev = pd.read_csv(path, nrows=1).iloc[0][["latitude", "longitude", "elevation"]]
        meta[city] = {"lat": lat, "lon": lon, "elev": elev}
        d = pd.read_csv(path, skiprows=3)
        d.columns = ["date"] + FEATURES
        d["city"] = city
        frames.append(d)
    df = pd.concat(frames, ignore_index=True)
    df["date"] = pd.to_datetime(df["date"])
    df = df.sort_values(["city", "date"]).reset_index(drop=True)
    df["year"] = df["date"].dt.year
    df["month"] = df["date"].dt.month
    # day-of-year on a 365-day calendar (Feb 29 treated as Feb 28)
    md = df["date"].dt.strftime("%m-%d").replace("02-29", "02-28")
    df["doy"] = pd.to_datetime("2001-" + md).dt.dayofyear
    return df, meta


def add_daily_normals(df):
    """Departure from a smoothed day-of-year normal (15-day window, 2015-2024)."""
    base = df[df["year"].between(*NORMAL_YEARS)]
    out = []
    for city, g in df.groupby("city"):
        clim = base[base["city"] == city].groupby("doy")[["temp_max", "temp_min"]].mean()
        clim = clim.reindex(range(1, 366)).interpolate()
        wrapped = pd.concat([clim.iloc[-7:], clim, clim.iloc[:7]])        # circular year
        smooth = wrapped.rolling(15, center=True).mean().iloc[7:-7]
        g = g.copy()
        g["norm_max"] = g["doy"].map(smooth["temp_max"])
        g["norm_min"] = g["doy"].map(smooth["temp_min"])
        out.append(g)
    df = pd.concat(out).sort_values(["city", "date"]).reset_index(drop=True)
    df["dep_max"] = df["temp_max"] - df["norm_max"]
    df["dep_min"] = df["temp_min"] - df["norm_min"]
    return df


def monthly_table(df):
    m = df.groupby(["city", "year", "month"]).agg(
        days=("date", "count"),
        avg_max=("temp_max", "mean"), avg_min=("temp_min", "mean"),
        rain=("precip", "sum"),
        rainy_days=("precip", lambda s: int((s >= RAINY_DAY_MM).sum())),
        humidity=("humidity", "mean"), wind=("wind_max", "mean"),
    ).reset_index()
    return m[m["days"] >= MIN_DAYS_IN_MONTH]


def monthly_normals(monthly):
    base = monthly[monthly["year"].between(*NORMAL_YEARS)]
    return base.groupby(["city", "month"])[["avg_max", "avg_min", "rain", "rainy_days", "humidity", "wind"]].mean()


