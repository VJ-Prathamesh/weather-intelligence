def build_trend_doc(city, g, events):
    base = g[g["year"].between(*NORMAL_YEARS)]
    annual = base.groupby("year").agg(avg_max=("temp_max", "mean"), avg_min=("temp_min", "mean"),
                                      rain=("precip", "sum"),
                                      rainy_days=("precip", lambda s: int((s >= RAINY_DAY_MM).sum())),
                                      hot_days=("temp_max", lambda s: int((s >= 40).sum())))
    hw = event_days_by_year(events, "Heatwave")
    annual["hw_days"] = [hw.get(y, 0) for y in annual.index]
    yrs = annual.index.values

    def slope(col):  # change per decade from a straight-line fit
        return np.polyfit(yrs, annual[col].values, 1)[0] * 10

    s_max, s_min, s_rain = slope("avg_max"), slope("avg_min"), slope("rain")

    def word(s, unit, small):
        if abs(s) < small:
            return "no clear change"
        return f"{'an increase' if s > 0 else 'a decrease'} of about {fmt(abs(s))} {unit} per decade"

    rain_pct = s_rain / annual["rain"].mean() * 100
    rows = [[y, fmt(r["avg_max"]), fmt(r["avg_min"]), fmt(r["rain"], 0), int(r["rainy_days"]),
             int(r["hot_days"]), int(r["hw_days"])] for y, r in annual.iterrows()]
    body = f"""# {city} year-over-year trends ({NORMAL_YEARS[0]}–{NORMAL_YEARS[1]})

Over {NORMAL_YEARS[0]}–{NORMAL_YEARS[1]}, a straight-line fit shows {word(s_max, '°C', 0.2)} in the average daily maximum
temperature in {city}, {word(s_min, '°C', 0.2)} in the average daily minimum, and
{"no clear change" if abs(rain_pct) < 10 else f"{'an increase' if rain_pct > 0 else 'a decrease'} of about {abs(rain_pct):.0f}% per decade"}
in annual rainfall. The warmest year was {annual['avg_max'].idxmax()} (average maximum {fmt(annual['avg_max'].max())}°C)
and the coolest was {annual['avg_max'].idxmin()} ({fmt(annual['avg_max'].min())}°C).

**Caution:** 10 years is too short to separate a climate trend from natural year-to-year variability
(for example El Niño and La Niña years). Treat these figures as a description of this decade, not a long-term trend.

## Annual values

{md_table(["Year", "Avg max °C", "Avg min °C", "Rain mm", "Rainy days", "Days ≥ 40°C", "Heatwave days"], rows)}
"""
    write_doc(f"trends/{city}_trends.md", {"doc_type": "trends", "city": city}, body)


def build_onset_doc(city, g):
    ne = CITY_INFO[city]["main_rain"] == "northeast"
    start_md, months = ((10, 10), [10, 11, 12]) if ne else ((5, 20), [6, 7, 8, 9])
    season_name = "northeast monsoon (October–December)" if ne else "southwest monsoon (June–September)"
    rows, totals = [], {}
    for y, w in g[g["year"] <= NORMAL_YEARS[1]].groupby("year"):
        w = w.reset_index(drop=True)
        rain5 = w["precip"].rolling(5).sum().shift(-4)
        rainy5 = (w["precip"] >= RAINY_DAY_MM).astype(int).rolling(5).sum().shift(-4)
        ok = (w["date"] >= pd.Timestamp(y, *start_md)) & (rain5 >= 30) & (rainy5 >= 3)
        onset = day(w.loc[ok.idxmax(), "date"]) if ok.any() else "not detected"
        totals[y] = w.loc[w["month"].isin(months), "precip"].sum()
        rows.append([y, onset, fmt(totals[y], 0)])
    normal = np.mean(list(totals.values()))
    for r in rows:
        r.append(f"{totals[r[0]] / normal * 100:.0f}%")
    body = f"""# {city} rainy-season onset and seasonal rainfall

{city}'s main rainy season is the **{season_name}**. The table gives, for each year, an estimated onset date of
sustained rain and the total rainfall of the season. The {NORMAL_YEARS[0]}–{NORMAL_YEARS[1]} average seasonal rainfall is
{normal:.0f} mm. The wettest season was {max(totals, key=totals.get)} ({max(totals.values()):.0f} mm) and the driest
was {min(totals, key=totals.get)} ({min(totals.values()):.0f} mm).

The onset date is a **rainfall-based estimate, not the official IMD monsoon onset date** (see the event definitions document).

{md_table(["Year", "Estimated onset", "Season rainfall mm", "% of average"], rows)}
"""
    write_doc(f"monsoon/{city}_rainy_season.md", {"doc_type": "rainy_season", "city": city}, body)


