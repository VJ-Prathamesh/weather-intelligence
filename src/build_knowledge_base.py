def build_seasonal_docs(city, g, monthly):
    cm = monthly[monthly["city"] == city].copy()
    cm["season_year"] = np.where(cm["month"] == 12, cm["year"] + 1, cm["year"])
    for sname, months in SEASONS.items():
        sub = cm[cm["month"].isin(months)]
        complete = sub.groupby("season_year").filter(lambda x: len(x) == len(months))
        if complete.empty:
            continue
        agg = complete.groupby("season_year").agg(avg_max=("avg_max", "mean"), avg_min=("avg_min", "mean"),
                                                  rain=("rain", "sum"), rainy_days=("rainy_days", "sum"))
        normal = agg.loc[agg.index.to_series().between(*NORMAL_YEARS)].mean()
        mlabel = f"{MONTHS[months[0] - 1]}–{MONTHS[months[-1] - 1]}"
        for sy, r in agg.iterrows():
            label = f"{sname} {sy - 1}-{str(sy)[2:]}" if sname == "Winter" else f"{sname} {sy}"
            first_month = months[0]
            start = pd.Timestamp(sy - 1 if first_month == 12 else sy, first_month, 1)
            end = pd.Timestamp(sy, months[-1], 1) + pd.offsets.MonthEnd(0)
            w = g[(g["date"] >= start) & (g["date"] <= end)]
            hot, cold, wet = w["temp_max"].idxmax(), w["temp_min"].idxmin(), w["precip"].idxmax()
            anom = r["avg_max"] - normal["avg_max"]
            body = f"""# {city} seasonal summary: {label} ({mlabel})

The {label} season ({mlabel}) in {city} was **{temp_anomaly_words(anom)}** (average maximum {fmt(r['avg_max'])}°C,
{signed(anom)}°C versus the seasonal normal of {fmt(normal['avg_max'])}°C) with
**{rain_words(r['rain'], normal['rain'])}**: {fmt(r['rain'])} mm of rain on {int(r['rainy_days'])} rainy days
(seasonal normal {fmt(normal['rain'])} mm).

{md_table(["Measure", label, "Seasonal normal"], [
    ["Average max temperature", f"{fmt(r['avg_max'])} °C", f"{fmt(normal['avg_max'])} °C"],
    ["Average min temperature", f"{fmt(r['avg_min'])} °C", f"{fmt(normal['avg_min'])} °C"],
    ["Total rainfall", f"{fmt(r['rain'])} mm", f"{fmt(normal['rain'])} mm"],
    ["Rainy days", int(r["rainy_days"]), fmt(normal["rainy_days"])],
    ["Hottest day", f"{fmt(w.at[hot, 'temp_max'])} °C on {day(w.at[hot, 'date'])}", ""],
    ["Coldest night", f"{fmt(w.at[cold, 'temp_min'])} °C on {day(w.at[cold, 'date'])}", ""],
    ["Wettest day", f"{fmt(w.at[wet, 'precip'])} mm on {day(w.at[wet, 'date'])}", ""],
])}
"""
            slug = sname.lower().replace("-", "_")
            write_doc(f"seasonal/{city}/{city}_{sy}_{slug}.md",
                      {"doc_type": "seasonal_summary", "city": city, "season": sname, "season_label": label,
                       "year": int(sy), "period_start": day(start), "period_end": day(end)}, body)


def build_event_docs(city, g, events):
    years = sorted(g["year"].unique())
    for y in years:
        yevs = [e for e in events if e["start"].year == y]
        sections = []
        for et in EVENT_TYPES:
            evs = [e for e in yevs if e["type"] == et]
            if not evs:
                sections.append(f"## {et}\n\nNo {et.lower()} event was detected in {city} in {y}.")
                continue
            items = "\n\n".join(f"### {et} in {city}: {day(e['start'])} to {day(e['end'])} ({plural(e['days'], 'day')})\n\n{e['text']}"
                                for e in evs)
            sections.append(f"## {et} ({len(evs)} events, {sum(e['days'] for e in evs)} days)\n\n{items}")
        counts = ", ".join(f"{sum(1 for e in yevs if e['type'] == et)} {et.lower()}" for et in EVENT_TYPES)
        partial = " (the dataset only has 1 January 2025 for this year)" if y > NORMAL_YEARS[1] else ""
        body = f"""# {city} weather events in {y}

Rule-based weather events detected in {city} during {y}{partial}: {counts} events.
Definitions are in the event definitions document.

""" + "\n\n".join(sections)
        write_doc(f"events/{city}/{city}_{y}_events.md",
                  {"doc_type": "event_log", "city": city, "year": int(y)}, body)

    rows = []
    for y in years:
        if y > NORMAL_YEARS[1]:
            continue
        rows.append([y] + [f"{sum(1 for e in events if e['type'] == et and e['start'].year == y)} "
                           f"({sum(e['days'] for e in events if e['type'] == et and e['start'].year == y)} d)"
                           for et in EVENT_TYPES])
    hw = event_days_by_year(events, "Heatwave")
    worst = max(hw, key=hw.get) if hw else None
    worst_txt = f"The year with the most heatwave days was {worst} ({hw[worst]} days)." if worst else \
        f"No heatwave was detected in {city} in {NORMAL_YEARS[0]}–{NORMAL_YEARS[1]}."
    body = f"""# {city} weather events summary by year

Number of rule-based weather events per year in {city}, {NORMAL_YEARS[0]}–{NORMAL_YEARS[1]}, with the total number
of event days in brackets. {worst_txt}

{md_table(["Year"] + EVENT_TYPES, rows)}
"""
    write_doc(f"events/{city}/{city}_events_summary.md", {"doc_type": "event_summary", "city": city}, body)


