def detect_events(g, zone):
    """All rule-based events for one city. Returns a list of dicts."""
    g = g.reset_index(drop=True)
    tmax, tmin, dmax, dmin = g["temp_max"], g["temp_min"], g["dep_max"], g["dep_min"]
    events = []

    if zone == "plains":
        hw = ((tmax >= 40) & (dmax >= 4.5)) | (tmax >= 45)
        hw_sev = ((tmax >= 40) & (dmax >= 6.5)) | (tmax >= 47)
        cw = ((tmin <= 10) & (dmin <= -4.5)) | (tmin <= 4)
        cw_sev = ((tmin <= 10) & (dmin <= -6.5)) | (tmin <= 2)
    elif zone == "coastal":
        hw, hw_sev = (tmax >= 37) & (dmax >= 4.5), (tmax >= 37) & (dmax >= 6.5)
        cw, cw_sev = (tmin <= 15) & (dmin <= -4.5), (tmin <= 15) & (dmin <= -6.5)
    else:  # hills
        hw, hw_sev = (tmax >= 30) & (dmax >= 4.5), (tmax >= 30) & (dmax >= 6.5)
        cw, cw_sev = (tmin <= 0) & (dmin <= -4.5), (tmin <= 0) & (dmin <= -6.5)

    for s, e in find_runs(hw.values):
        if e - s + 1 < 2:
            continue
        w = g.iloc[s:e + 1]
        pk = w["temp_max"].idxmax()
        n_sev = int(hw_sev.iloc[s:e + 1].sum())
        events.append({
            "type": "Heatwave", "start": w["date"].iloc[0], "end": w["date"].iloc[-1], "days": e - s + 1,
            "text": (f"Peak maximum temperature {fmt(g.at[pk, 'temp_max'])}°C on {day(g.at[pk, 'date'])}, "
                     f"up to {fmt(w['dep_max'].max())}°C above the normal for those dates. "
                     f"Severe-heatwave criteria were met on {n_sev} of {e - s + 1} days."),
        })

    for s, e in find_runs(cw.values):
        if e - s + 1 < 2:
            continue
        w = g.iloc[s:e + 1]
        pk = w["temp_min"].idxmin()
        n_sev = int(cw_sev.iloc[s:e + 1].sum())
        events.append({
            "type": "Cold wave", "start": w["date"].iloc[0], "end": w["date"].iloc[-1], "days": e - s + 1,
            "text": (f"Lowest minimum temperature {fmt(g.at[pk, 'temp_min'])}°C on {day(g.at[pk, 'date'])}, "
                     f"up to {fmt(-w['dep_min'].min())}°C below the normal for those dates. "
                     f"Severe-cold-wave criteria were met on {n_sev} of {e - s + 1} days."),
        })

    for s, e in find_runs((g["precip"] >= 64.5).values):
        w = g.iloc[s:e + 1]
        pk = w["precip"].idxmax()
        p = g.at[pk, "precip"]
        cat = "extremely heavy" if p >= 204.5 else "very heavy" if p >= 115.6 else "heavy"
        events.append({
            "type": "Heavy rain", "start": w["date"].iloc[0], "end": w["date"].iloc[-1], "days": e - s + 1,
            "text": (f"Total rainfall {fmt(w['precip'].sum())} mm over {plural(e - s + 1, 'day')}. "
                     f"Wettest day {day(g.at[pk, 'date'])} with {fmt(p)} mm ({cat} rain by IMD categories)."),
        })

    season = [10, 11, 12] if CITY_INFO[g["city"].iloc[0]]["main_rain"] == "northeast" else [6, 7, 8, 9]
    dry = g["month"].isin(season) & (g["precip"] < RAINY_DAY_MM)
    for s, e in find_runs(dry.values):
        if e - s + 1 < 10:
            continue
        w = g.iloc[s:e + 1]
        events.append({
            "type": "Dry spell", "start": w["date"].iloc[0], "end": w["date"].iloc[-1], "days": e - s + 1,
            "text": (f"{e - s + 1} consecutive days with less than {RAINY_DAY_MM} mm of rain during the main rainy season "
                     f"(total {fmt(w['precip'].sum())} mm in the spell)."),
        })

    for s, e in find_runs((g["wind_max"] >= 40).values):
        w = g.iloc[s:e + 1]
        pk = w["wind_max"].idxmax()
        events.append({
            "type": "High wind", "start": w["date"].iloc[0], "end": w["date"].iloc[-1], "days": e - s + 1,
            "text": (f"Daily maximum wind reached {fmt(g.at[pk, 'wind_max'])} km/h on {day(g.at[pk, 'date'])}; "
                     f"rainfall during the event {fmt(w['precip'].sum())} mm."),
        })

    for s, e in find_runs(g["weathercode"].between(71, 77).values):
        w = g.iloc[s:e + 1]
        heaviest = WMO_CODES[int(w["weathercode"].max())].lower()
        events.append({
            "type": "Snowfall", "start": w["date"].iloc[0], "end": w["date"].iloc[-1], "days": e - s + 1,
            "text": (f"Snowfall reported on {plural(e - s + 1, 'consecutive day')}, heaviest category {heaviest}; "
                     f"lowest minimum temperature {fmt(w['temp_min'].min())}°C."),
        })

    return sorted(events, key=lambda ev: (ev["start"], ev["type"]))


def event_days_by_year(events, etype):
    counts = {}
    for ev in events:
        if ev["type"] == etype:
            counts[ev["start"].year] = counts.get(ev["start"].year, 0) + ev["days"]
    return counts


