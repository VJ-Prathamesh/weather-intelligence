# ---------------------------------------------------------------- helpers

def fmt(x, nd=1):
    return f"{x:.{nd}f}"


def signed(x, nd=1):
    return f"{x:+.{nd}f}"


def md_table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |",
             "| " + " | ".join("---" for _ in headers) + " |"]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def front_matter(**meta):
    lines = ["---"]
    for k, v in meta.items():
        if v is not None:
            lines.append(f"{k}: {v}")
    lines.append(f"source: {SOURCE}")
    lines.append("---")
    return "\n".join(lines)


def write_doc(rel_path, meta, body):
    path = os.path.join(OUT_DIR, rel_path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(front_matter(**meta) + "\n\n" + body.strip() + "\n")


def find_runs(mask):
    """(start_idx, end_idx) of consecutive True values in a boolean array."""
    runs, start = [], None
    for i, v in enumerate(mask):
        if v and start is None:
            start = i
        elif not v and start is not None:
            runs.append((start, i - 1))
            start = None
    if start is not None:
        runs.append((start, len(mask) - 1))
    return runs


def plural(n, word):
    return f"{n} {word}" + ("" if n == 1 else "s")


def day(ts):
    return pd.Timestamp(ts).strftime("%Y-%m-%d")


def temp_anomaly_words(a):
    if a >= 2:   return "much warmer than usual"
    if a >= 1:   return "warmer than usual"
    if a <= -2:  return "much cooler than usual"
    if a <= -1:  return "cooler than usual"
    return "close to normal temperature"


def rain_words(total, normal):
    if normal < 10:
        return "dry, as is usual for this period" if total < 10 else "unusually wet for a normally dry period"
    pct = total / normal * 100
    if pct < 60:   return f"much drier than usual ({pct:.0f}% of normal rainfall)"
    if pct < 90:   return f"drier than usual ({pct:.0f}% of normal rainfall)"
    if pct <= 110: return f"near-normal rainfall ({pct:.0f}% of normal)"
    if pct <= 150: return f"wetter than usual ({pct:.0f}% of normal rainfall)"
    return f"much wetter than usual ({pct:.0f}% of normal rainfall)"


def weather_mix(codes):
    counts = codes.value_counts()
    return ", ".join(f"{WMO_CODES.get(int(c), f'code {int(c)}')} ({n} days)" for c, n in counts.head(3).items())


